"""Developer tool: build source/hd_font_data.h (HD lettering outlines) from Roboto Flex.

    python hd_font_data.py <RobotoFlex-Regular.ttf> <out.h>

Needs Pillow and numpy; not part of the build. Roboto Flex (SIL Open Font
License 1.1, licences/OFL-1.1-RobotoFlex.txt) is instanced at two styles,
each printable ASCII glyph is rendered at 512 px, traced at half coverage
(marching squares) and simplified (Douglas-Peucker, 0.3 px). Coordinates are
in 1/1024 em, x from the pen position, y down from the baseline. The output is
a Modified Version of the font and stays under the OFL.
"""
import sys, numpy as np
from PIL import Image, ImageDraw, ImageFont

SIZE, FIRST, LAST = 512, 33, 126
STYLES = [  # (name, axes): regular for menus and help; bold italic for results, names, HUD;
    # black for the menu title banners
    ('regular', {'Weight': 560, 'Width': 140}),
    ('bold italic', {'Weight': 800, 'Slant': -10, 'Width': 135}),
    ('black', {'Weight': 1000, 'Width': 140}),
]

def font(path, axes):
    f = ImageFont.truetype(path, SIZE)
    vals = []
    for a in f.get_variation_axes():
        n = a['name'].decode() if isinstance(a['name'], bytes) else a['name']
        vals.append(axes.get(n, a['default']))
    f.set_variation_by_axes(vals)
    return f

def trace(img):
    """Closed loops of the 0.5 iso-line, in pixel-centre coordinates."""
    H, W = img.shape
    a, b, c, d = img[:-1, :-1], img[:-1, 1:], img[1:, 1:], img[1:, :-1]
    case = (a >= .5) * 1 + (b >= .5) * 2 + (c >= .5) * 4 + (d >= .5) * 8
    cen = (a + b + c + d) / 4 >= .5
    jj, ii = np.mgrid[0:H - 1, 0:W - 1]
    T = (jj * W + ii) * 2; R = (jj * W + ii + 1) * 2 + 1; B = ((jj + 1) * W + ii) * 2; L = (jj * W + ii) * 2 + 1
    table = {1: [(L, T)], 2: [(T, R)], 3: [(L, R)], 4: [(R, B)], 6: [(T, B)], 7: [(L, B)], 8: [(B, L)],
             9: [(B, T)], 11: [(B, R)], 12: [(R, L)], 13: [(R, T)], 14: [(T, L)]}
    nxt = {}
    for k, segs in table.items():
        m = case == k
        for s, e in segs:
            nxt.update(zip(s[m].tolist(), e[m].tolist()))
    for k in (5, 10):
        for joined in (True, False):
            m = (case == k) & (cen == joined)
            if k == 5: segs = [(L, B), (R, T)] if joined else [(L, T), (R, B)]
            else: segs = [(T, L), (B, R)] if joined else [(T, R), (B, L)]
            for s, e in segs:
                nxt.update(zip(s[m].tolist(), e[m].tolist()))
    flat = img.ravel()
    def point(e):
        k = e >> 1; i, j = k % W, k // W
        if not e & 1:
            p, q = flat[j * W + i], flat[j * W + i + 1]; return (i + .5 + (.5 - p) / (q - p), j + .5)
        p, q = flat[j * W + i], flat[(j + 1) * W + i]; return (i + .5, j + .5 + (.5 - p) / (q - p))
    loops, seen = [], set()
    for e0 in nxt:
        if e0 in seen: continue
        pts, e = [], e0
        while e not in seen and e in nxt:
            seen.add(e); pts.append(point(e)); e = nxt[e]
        if len(pts) >= 3: loops.append(np.array(pts))
    return loops

def rdp(p, tol):
    if len(p) < 3: return p
    a, b = p[0], p[-1]; ab = b - a; n = np.hypot(*ab)
    v = p - a
    d = np.abs(ab[0] * v[:, 1] - ab[1] * v[:, 0]) / n if n > 1e-9 else np.hypot(*v.T)
    k = int(np.argmax(d))
    if d[k] <= tol: return np.array([a, b])
    return np.vstack([rdp(p[:k + 1], tol)[:-1], rdp(p[k:], tol)])

def simplify(loop, tol=.3):
    far = int(np.argmax(np.hypot(*(loop - loop[0]).T)))
    a = rdp(np.vstack([loop[:far + 1]]), tol); b = rdp(np.vstack([loop[far:], loop[:1]]), tol)
    return np.vstack([a[:-1], b[:-1]])

def main():
    src, out = sys.argv[1], sys.argv[2]
    data, index, advance = [], [], []
    for name, axes in STYLES:
        f = font(src, axes); row = []
        advance.append([int(round(f.getlength(chr(ch)) * 2)) for ch in range(32, LAST + 1)])
        for ch in range(FIRST, LAST + 1):
            img = Image.new('L', (1100, 1000), 0)
            ox, oy = 250, 700
            ImageDraw.Draw(img).text((ox, oy), chr(ch), font=f, fill=255, anchor='ls')
            loops = [simplify(l) for l in trace(np.asarray(img, np.float64) / 255.0)]
            row.append(len(data)); data.append(len(loops))
            for l in loops:
                data.append(len(l))
                for x, y in l:
                    data += [int(round((x - ox) * 2)), int(round((y - oy) * 2))]
        index.append(row)
    lines = ['/* HD lettering outlines: printable ASCII in three styles of Roboto Flex.',
             ' * Generated by tools/hd_font_data.py; do not edit. A Modified Version of',
             ' * Roboto Flex, Copyright 2017 The Roboto Flex Project Authors',
             ' * (https://github.com/TypeNetwork/Roboto-Flex), licensed under the SIL Open',
             ' * Font License 1.1 (licences/OFL-1.1-RobotoFlex.txt). Roboto is a trademark',
             ' * of Google. Styles: ' + ', '.join(n for n, _ in STYLES) + '.',
             ' * Per glyph: contour count, then per contour: point count and x,y pairs in',
             ' * 1/1024 em (x from the pen position, y down from the baseline).',
             ' * rr_hd_advance: advance width from the space (32) on, 1/1024 em. */',
             '#pragma once', '#include <stdint.h>   /* C and C++: the launcher draws its titles with it too */',
             'enum { RR_HD_FIRST = %d, RR_HD_LAST = %d, RR_HD_STYLES = %d };' % (FIRST, LAST, len(STYLES)),
             'static const uint32_t rr_hd_index[RR_HD_STYLES][RR_HD_LAST - RR_HD_FIRST + 1] = {']
    for row in index:
        lines.append(' {' + ','.join(map(str, row)) + '},')
    lines.append('};')
    lines.append('static const int16_t rr_hd_advance[RR_HD_STYLES][RR_HD_LAST - 31] = {')
    for row in advance:
        lines.append(' {' + ','.join(map(str, row)) + '},')
    lines.append('};')
    lines.append('static const int16_t rr_hd_data[%d] = {' % len(data))
    for i in range(0, len(data), 24):
        lines.append(' ' + ','.join(map(str, data[i:i + 24])) + ',')
    lines.append('};')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('values', len(data))

if __name__ == '__main__':
    main()
